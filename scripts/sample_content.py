@dataclass(frozen=True)
class Fact:
    key: str
    doc: str
    kind: str
    question: str
    expect_found: bool
    clause: str = ""  # номер пункта, который заменяется текстом факта, например "4.2.1"
    text: str = ""
    locate: str = ""  # фрагмент текста, по которому ищутся страницы ответа
    section: str | None = None
    expect_contains: str = ""
    cross_page: bool = False
    # другие места, где факт тоже честно указан: (текст для поиска страниц, раздел)
    also_in: tuple[tuple[str, str], ...] = ()


